// Helper to create an ISO date string offset by days and hours
const getDateOffset = (daysAgo: number, hoursOffset: number = 10, minutesOffset: number = 30): string => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  d.setHours(hoursOffset, minutesOffset, 0, 0);
  return d.toISOString();
};

